-- =============================================================================
-- Auto Timetable / Exam Scheduler (ATES)
-- PostgreSQL Database Schema for Supabase (PostgreSQL 15+)
-- Specification Reference: docs/SRS.pdf (Section 5.1, Table 30, Appendix A)
-- =============================================================================

BEGIN;

-- Ensure UTC storage for timestamps per DB-8
SET TIME ZONE 'UTC';

-- =============================================================================
-- 1. departments (SRS 5.1.3.1)
-- Academic departments that own courses, batches and instructors.
-- =============================================================================
CREATE TABLE IF NOT EXISTS departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(10)  NOT NULL UNIQUE,
    name          VARCHAR(100) NOT NULL
);

-- =============================================================================
-- 2. academic_terms (SRS 5.1.3.2, FR-2.6)
-- Semesters for which schedules are produced.
-- =============================================================================
CREATE TABLE IF NOT EXISTS academic_terms (
    term_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL UNIQUE,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    status     VARCHAR(10) NOT NULL DEFAULT 'Planned',
    CONSTRAINT chk_academic_terms_dates
        CHECK (end_date > start_date),
    CONSTRAINT chk_academic_terms_status
        CHECK (status IN ('Planned', 'Active', 'Closed'))
);

-- At most one Active term at any time (SRS 5.1.3.2, 5.1.5, FR-2.6)
CREATE UNIQUE INDEX IF NOT EXISTS uq_academic_terms_single_active
    ON academic_terms ((status))
    WHERE status = 'Active';

-- =============================================================================
-- 3. time_slots (SRS 5.1.3.3, FR-2.7)
-- Weekly slot grid of a term.
-- =============================================================================
CREATE TABLE IF NOT EXISTS time_slots (
    slot_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id      INTEGER     NOT NULL REFERENCES academic_terms(term_id) ON DELETE RESTRICT,
    day_of_week  SMALLINT    NOT NULL,
    slot_index   SMALLINT    NOT NULL,
    start_time   TIME        NOT NULL,
    end_time     TIME        NOT NULL,
    is_blocked   BOOLEAN     NOT NULL DEFAULT FALSE,
    block_reason VARCHAR(50) NULL,
    CONSTRAINT chk_time_slots_day_of_week
        CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_time_slots_slot_index
        CHECK (slot_index > 0),
    CONSTRAINT chk_time_slots_times
        CHECK (end_time > start_time),
    CONSTRAINT chk_time_slots_block_reason
        CHECK (NOT is_blocked OR (block_reason IS NOT NULL AND length(trim(block_reason)) > 0)),
    CONSTRAINT uq_time_slots_term_day_slot
        UNIQUE (term_id, day_of_week, slot_index)
);

-- =============================================================================
-- 4. batches (SRS 5.1.3.4, FR-2.5)
-- Student batches and sections.
-- =============================================================================
CREATE TABLE IF NOT EXISTS batches (
    batch_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER     NOT NULL REFERENCES departments(department_id) ON DELETE RESTRICT,
    program_code  VARCHAR(10) NOT NULL,
    batch_year    SMALLINT    NOT NULL,
    section       VARCHAR(5)  NOT NULL,
    strength      SMALLINT    NOT NULL,
    is_active     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_batches_strength
        CHECK (strength > 0),
    CONSTRAINT uq_batches_program_year_section
        UNIQUE (program_code, batch_year, section)
);

-- =============================================================================
-- 5. courses (SRS 5.1.3.5, FR-2.1, FR-2.2)
-- Course catalogue.
-- =============================================================================
CREATE TABLE IF NOT EXISTS courses (
    course_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code   VARCHAR(15)  NOT NULL UNIQUE,
    title         VARCHAR(150) NOT NULL,
    department_id INTEGER      NOT NULL REFERENCES departments(department_id) ON DELETE RESTRICT,
    credit_hours  SMALLINT     NOT NULL,
    lecture_hours SMALLINT     NOT NULL DEFAULT 0,
    lab_hours     SMALLINT     NOT NULL DEFAULT 0,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_courses_credit_hours
        CHECK (credit_hours >= 0),
    CONSTRAINT chk_courses_lecture_hours
        CHECK (lecture_hours >= 0),
    CONSTRAINT chk_courses_lab_hours
        CHECK (lab_hours >= 0),
    CONSTRAINT chk_courses_total_contact_hours
        CHECK (lecture_hours + lab_hours > 0)
);

-- =============================================================================
-- 6. instructors (SRS 5.1.3.6, FR-2.3)
-- Teaching staff.
-- =============================================================================
CREATE TABLE IF NOT EXISTS instructors (
    instructor_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id    INTEGER      NOT NULL REFERENCES departments(department_id) ON DELETE RESTRICT,
    full_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(120) NOT NULL UNIQUE,
    max_daily_hours  SMALLINT     NOT NULL DEFAULT 4,
    max_weekly_hours SMALLINT     NOT NULL DEFAULT 18,
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_instructors_max_daily_hours
        CHECK (max_daily_hours > 0),
    CONSTRAINT chk_instructors_max_weekly_hours
        CHECK (max_weekly_hours >= max_daily_hours)
);

-- =============================================================================
-- 7. instructor_availability (SRS 5.1.3.7, FR-3.1 to FR-3.3)
-- Slots in which an instructor is available or unavailable.
-- =============================================================================
CREATE TABLE IF NOT EXISTS instructor_availability (
    availability_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id   INTEGER NOT NULL REFERENCES instructors(instructor_id) ON DELETE RESTRICT,
    slot_id         INTEGER NOT NULL REFERENCES time_slots(slot_id) ON DELETE CASCADE,
    is_available    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_instructor_availability_instructor_slot
        UNIQUE (instructor_id, slot_id)
);

-- =============================================================================
-- 8. rooms (SRS 5.1.3.8, FR-2.4)
-- Lecture rooms, laboratories and exam halls.
-- =============================================================================
CREATE TABLE IF NOT EXISTS rooms (
    room_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(20) NOT NULL UNIQUE,
    building  VARCHAR(50) NOT NULL,
    capacity  SMALLINT    NOT NULL,
    room_type VARCHAR(12) NOT NULL,
    is_active BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_rooms_capacity
        CHECK (capacity > 0),
    CONSTRAINT chk_rooms_room_type
        CHECK (room_type IN ('Lecture', 'Lab', 'Exam Hall'))
);

-- =============================================================================
-- 9. users (SRS 5.1.3.9, FR-1.1 to FR-1.7, 5.1.5)
-- User accounts and roles.
-- =============================================================================
CREATE TABLE IF NOT EXISTS users (
    user_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(40)  NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(120) NOT NULL UNIQUE,
    role            VARCHAR(15)  NOT NULL,
    instructor_id   INTEGER      NULL UNIQUE REFERENCES instructors(instructor_id) ON DELETE RESTRICT,
    batch_id        INTEGER      NULL REFERENCES batches(batch_id) ON DELETE RESTRICT,
    account_status  VARCHAR(12)  NOT NULL DEFAULT 'Active',
    failed_attempts SMALLINT     NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP    NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_role
        CHECK (role IN ('Administrator', 'Coordinator', 'Approver', 'Faculty', 'Student')),
    CONSTRAINT chk_users_account_status
        CHECK (account_status IN ('Active', 'Locked', 'Deactivated')),
    CONSTRAINT chk_users_failed_attempts
        CHECK (failed_attempts >= 0),
    CONSTRAINT chk_users_faculty_link
        CHECK (role <> 'Faculty' OR instructor_id IS NOT NULL),
    CONSTRAINT chk_users_student_link
        CHECK (role <> 'Student' OR batch_id IS NOT NULL)
);

-- =============================================================================
-- 10. course_offerings (SRS 5.1.3.10, FR-2.8, FR-2.9)
-- A course taught to one batch by one instructor in one term.
-- =============================================================================
CREATE TABLE IF NOT EXISTS course_offerings (
    offering_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id        INTEGER  NOT NULL REFERENCES academic_terms(term_id) ON DELETE RESTRICT,
    course_id      INTEGER  NOT NULL REFERENCES courses(course_id) ON DELETE RESTRICT,
    batch_id       INTEGER  NOT NULL REFERENCES batches(batch_id) ON DELETE RESTRICT,
    instructor_id  INTEGER  NOT NULL REFERENCES instructors(instructor_id) ON DELETE RESTRICT,
    enrolled_count SMALLINT NOT NULL,
    CONSTRAINT chk_course_offerings_enrolled_count
        CHECK (enrolled_count > 0),
    CONSTRAINT uq_course_offerings_term_course_batch
        UNIQUE (term_id, course_id, batch_id),
    -- Supports composite FK from timetable_entries to guarantee DB-2 copy consistency
    CONSTRAINT uq_course_offerings_offering_instructor_batch
        UNIQUE (offering_id, instructor_id, batch_id)
);

-- =============================================================================
-- 11. enrollments (SRS 5.1.3.11, FR-2.10)
-- Optional student-to-offering links used for exam clashes.
-- =============================================================================
CREATE TABLE IF NOT EXISTS enrollments (
    enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offering_id   INTEGER NOT NULL REFERENCES course_offerings(offering_id) ON DELETE CASCADE,
    student_id    INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_enrollments_offering_student
        UNIQUE (offering_id, student_id)
);

-- =============================================================================
-- 12. scheduling_configs (SRS 5.1.3.12, FR-5.5, FR-5.6)
-- Named configuration of a term and schedule type.
-- =============================================================================
CREATE TABLE IF NOT EXISTS scheduling_configs (
    config_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id             INTEGER     NOT NULL REFERENCES academic_terms(term_id) ON DELETE RESTRICT,
    schedule_type       VARCHAR(10) NOT NULL,
    name                VARCHAR(60) NOT NULL,
    solver_time_limit_s SMALLINT    NOT NULL DEFAULT 120,
    random_seed         INTEGER     NOT NULL DEFAULT 1,
    created_by          INTEGER     NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    created_at          TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_scheduling_configs_schedule_type
        CHECK (schedule_type IN ('Timetable', 'Exam')),
    CONSTRAINT chk_scheduling_configs_solver_time_limit
        CHECK (solver_time_limit_s BETWEEN 10 AND 600),
    CONSTRAINT uq_scheduling_configs_term_type_name
        UNIQUE (term_id, schedule_type, name)
);

-- =============================================================================
-- 13. constraint_rules (SRS 5.1.3.13, FR-5.1 to FR-5.4)
-- Constraints of a configuration with enable flag, weight and parameter.
-- =============================================================================
CREATE TABLE IF NOT EXISTS constraint_rules (
    rule_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id   INTEGER    NOT NULL REFERENCES scheduling_configs(config_id) ON DELETE CASCADE,
    rule_code   VARCHAR(6) NOT NULL,
    rule_type   VARCHAR(4) NOT NULL,
    is_enabled  BOOLEAN    NOT NULL DEFAULT TRUE,
    weight      SMALLINT   NOT NULL DEFAULT 0,
    param_value INTEGER    NULL,
    CONSTRAINT chk_constraint_rules_rule_type
        CHECK (rule_type IN ('Hard', 'Soft')),
    CONSTRAINT chk_constraint_rules_weight
        CHECK (weight BETWEEN 0 AND 10),
    CONSTRAINT chk_constraint_rules_mandatory_enabled
        CHECK (NOT (rule_code IN ('H01', 'H02', 'H03', 'H08', 'E01', 'E04', 'E05') AND is_enabled = FALSE)),
    CONSTRAINT uq_constraint_rules_config_code
        UNIQUE (config_id, rule_code)
);

-- =============================================================================
-- 14. schedules (SRS 5.1.3.14, FR-6.2, FR-6.8, FR-9.1 to FR-9.3)
-- One generated version of a timetable or exam schedule.
-- =============================================================================
CREATE TABLE IF NOT EXISTS schedules (
    schedule_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id         INTEGER       NOT NULL REFERENCES academic_terms(term_id) ON DELETE RESTRICT,
    config_id       INTEGER       NOT NULL REFERENCES scheduling_configs(config_id) ON DELETE RESTRICT,
    schedule_type   VARCHAR(10)   NOT NULL,
    version_no      SMALLINT      NOT NULL,
    status          VARCHAR(12)   NOT NULL DEFAULT 'Draft',
    solver_status   VARCHAR(15)   NULL,
    objective_score NUMERIC(10,2) NULL,
    run_seconds     NUMERIC(8,2)  NULL,
    generated_by    INTEGER       NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    generated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_by     INTEGER       NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    published_at    TIMESTAMP     NULL,
    CONSTRAINT chk_schedules_schedule_type
        CHECK (schedule_type IN ('Timetable', 'Exam')),
    CONSTRAINT chk_schedules_version_no
        CHECK (version_no > 0),
    CONSTRAINT chk_schedules_status
        CHECK (status IN ('Draft', 'Generating', 'Infeasible', 'Generated', 'Published', 'Archived')),
    CONSTRAINT chk_schedules_solver_status
        CHECK (solver_status IS NULL OR solver_status IN ('optimal', 'feasible', 'infeasible', 'unknown', 'interrupted')),
    CONSTRAINT uq_schedules_term_type_version
        UNIQUE (term_id, schedule_type, version_no)
);

-- At most one Published schedule per (term_id, schedule_type) (SRS 5.1.3.14, FR-9.3)
CREATE UNIQUE INDEX IF NOT EXISTS uq_schedules_one_published_per_term_type
    ON schedules (term_id, schedule_type)
    WHERE status = 'Published';

-- =============================================================================
-- 15. timetable_entries (SRS 5.1.3.15, DB-2, FR-6.3, FR-8.3)
-- One scheduled slot of a class session (a lab block of k slots has k rows).
-- =============================================================================
CREATE TABLE IF NOT EXISTS timetable_entries (
    entry_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id        INTEGER    NOT NULL REFERENCES schedules(schedule_id) ON DELETE CASCADE,
    offering_id        INTEGER    NOT NULL REFERENCES course_offerings(offering_id) ON DELETE RESTRICT,
    instructor_id      INTEGER    NOT NULL REFERENCES instructors(instructor_id) ON DELETE RESTRICT,
    batch_id           INTEGER    NOT NULL REFERENCES batches(batch_id) ON DELETE RESTRICT,
    room_id            INTEGER    NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    slot_id            INTEGER    NOT NULL REFERENCES time_slots(slot_id) ON DELETE RESTRICT,
    session_type       VARCHAR(7) NOT NULL,
    is_locked          BOOLEAN    NOT NULL DEFAULT FALSE,
    is_manual_override BOOLEAN    NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_timetable_entries_session_type
        CHECK (session_type IN ('Lecture', 'Lab')),
    -- Guarantee instructor_id and batch_id match the parent offering (DB-2)
    CONSTRAINT fk_timetable_entries_offering_instructor_batch
        FOREIGN KEY (offering_id, instructor_id, batch_id)
        REFERENCES course_offerings(offering_id, instructor_id, batch_id) ON DELETE RESTRICT,
    -- Database-level clash prevention (H01, H02, H03 / SRS 5.1.3.15)
    CONSTRAINT uq_timetable_entries_schedule_room_slot
        UNIQUE (schedule_id, room_id, slot_id),
    CONSTRAINT uq_timetable_entries_schedule_instructor_slot
        UNIQUE (schedule_id, instructor_id, slot_id),
    CONSTRAINT uq_timetable_entries_schedule_batch_slot
        UNIQUE (schedule_id, batch_id, slot_id)
);

-- =============================================================================
-- 16. exam_slots (SRS 5.1.3.16, FR-5.7)
-- Exam sessions (date and time window) of a term.
-- =============================================================================
CREATE TABLE IF NOT EXISTS exam_slots (
    exam_slot_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id      INTEGER     NOT NULL REFERENCES academic_terms(term_id) ON DELETE RESTRICT,
    exam_date    DATE        NOT NULL,
    start_time   TIME        NOT NULL,
    end_time     TIME        NOT NULL,
    label        VARCHAR(30) NULL,
    CONSTRAINT chk_exam_slots_times
        CHECK (end_time > start_time),
    CONSTRAINT uq_exam_slots_term_date_start
        UNIQUE (term_id, exam_date, start_time)
);

-- =============================================================================
-- 17. exam_entries (SRS 5.1.3.17, FR-7.2, FR-7.7)
-- Assignment of a course exam to an exam session.
-- =============================================================================
CREATE TABLE IF NOT EXISTS exam_entries (
    exam_entry_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id   INTEGER  NOT NULL REFERENCES schedules(schedule_id) ON DELETE CASCADE,
    course_id     INTEGER  NOT NULL REFERENCES courses(course_id) ON DELETE RESTRICT,
    exam_slot_id  INTEGER  NOT NULL REFERENCES exam_slots(exam_slot_id) ON DELETE RESTRICT,
    student_count SMALLINT NOT NULL,
    is_locked     BOOLEAN  NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_exam_entries_student_count
        CHECK (student_count > 0),
    CONSTRAINT uq_exam_entries_schedule_course
        UNIQUE (schedule_id, course_id)
);

-- =============================================================================
-- 18. exam_room_allocations (SRS 5.1.3.18, FR-7.4)
