-- 1. Enforce append-only immutability on audit_logs and import_logs (DB-5, FR-12.3)
CREATE OR REPLACE FUNCTION fn_prevent_log_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Table % is append-only; UPDATE and DELETE are prohibited (FR-12.3, DB-5).', TG_TABLE_NAME;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_logs_immutable ON audit_logs;
CREATE TRIGGER trg_audit_logs_immutable
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_log_mutation();

DROP TRIGGER IF EXISTS trg_import_logs_immutable ON import_logs;
CREATE TRIGGER trg_import_logs_immutable
    BEFORE UPDATE OR DELETE ON import_logs
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_log_mutation();

-- 2. Reject overlapping exam_slots on the same date in the same term (FR-5.7)
CREATE OR REPLACE FUNCTION fn_check_exam_slot_overlap()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM exam_slots es
        WHERE es.term_id = NEW.term_id
          AND es.exam_date = NEW.exam_date
          AND es.exam_slot_id <> COALESCE(NEW.exam_slot_id, -1)
          AND NEW.start_time < es.end_time
          AND es.start_time < NEW.end_time
    ) THEN
        RAISE EXCEPTION 'Exam session overlaps with an existing session on % (FR-5.7).', NEW.exam_date;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_exam_slots_no_overlap ON exam_slots;
CREATE TRIGGER trg_exam_slots_no_overlap
    BEFORE INSERT OR UPDATE ON exam_slots
    FOR EACH ROW EXECUTE FUNCTION fn_check_exam_slot_overlap();

-- 3. Enforce seats_allocated <= room.capacity on exam_room_allocations (SRS 5.1.3.18, E03)
CREATE OR REPLACE FUNCTION fn_check_exam_room_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_capacity SMALLINT;
BEGIN
    SELECT capacity INTO v_capacity
    FROM rooms
    WHERE room_id = NEW.room_id;

    IF NEW.seats_allocated > v_capacity THEN
        RAISE EXCEPTION 'seats_allocated (%) exceeds room capacity (%) for room_id % (E03).',
            NEW.seats_allocated, v_capacity, NEW.room_id;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_exam_room_allocations_capacity ON exam_room_allocations;
CREATE TRIGGER trg_exam_room_allocations_capacity
    BEFORE INSERT OR UPDATE ON exam_room_allocations
    FOR EACH ROW EXECUTE FUNCTION fn_check_exam_room_capacity();

-- 4. Protect Published and Archived schedule entries from in-place modification (SRS 5.1.5, SAF-4)
CREATE OR REPLACE FUNCTION fn_prevent_published_schedule_entry_edit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_schedule_id INTEGER;
    v_status      VARCHAR(12);
BEGIN
    IF TG_TABLE_NAME = 'exam_room_allocations' THEN
        SELECT ee.schedule_id INTO v_schedule_id
        FROM exam_entries ee
        WHERE ee.exam_entry_id = COALESCE(NEW.exam_entry_id, OLD.exam_entry_id);
    ELSE
        v_schedule_id := COALESCE(NEW.schedule_id, OLD.schedule_id);
    END IF;

    SELECT status INTO v_status
    FROM schedules
    WHERE schedule_id = v_schedule_id;

    IF v_status IN ('Published', 'Archived') THEN
        RAISE EXCEPTION 'Entries of a % schedule (schedule_id=%) are read-only; create a new version instead (SAF-4).',
            v_status, v_schedule_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_timetable_entries_protect_published ON timetable_entries;
CREATE TRIGGER trg_timetable_entries_protect_published
    BEFORE INSERT OR UPDATE OR DELETE ON timetable_entries
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_published_schedule_entry_edit();

DROP TRIGGER IF EXISTS trg_exam_entries_protect_published ON exam_entries;
CREATE TRIGGER trg_exam_entries_protect_published
    BEFORE INSERT OR UPDATE OR DELETE ON exam_entries
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_published_schedule_entry_edit();

DROP TRIGGER IF EXISTS trg_exam_allocations_protect_published ON exam_room_allocations;
CREATE TRIGGER trg_exam_allocations_protect_published
    BEFORE INSERT OR UPDATE OR DELETE ON exam_room_allocations
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_published_schedule_entry_edit();

-- =============================================================================
-- Default Constraint Seeding Helper (SRS FR-5.1, Appendix A.1 & A.5)
-- Populates H01-H10 & S01-S06 (Timetable) or E01-E05 & ES01-ES03 (Exam)
-- with soft weights defaulting to 5 and default param_values (S03=5, S04=3, E02=2).
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_seed_default_constraint_rules(p_config_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_schedule_type VARCHAR(10);
BEGIN
    SELECT schedule_type INTO v_schedule_type
    FROM scheduling_configs
    WHERE config_id = p_config_id;

    IF v_schedule_type = 'Timetable' THEN
        INSERT INTO constraint_rules (config_id, rule_code, rule_type, is_enabled, weight, param_value)
        VALUES
            (p_config_id, 'H01', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H02', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H03', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H04', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H05', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H06', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H07', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H08', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H09', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'H10', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'S01', 'Soft', TRUE, 5, NULL),
            (p_config_id, 'S02', 'Soft', TRUE, 5, NULL),
            (p_config_id, 'S03', 'Soft', TRUE, 5, 5),
            (p_config_id, 'S04', 'Soft', TRUE, 5, 3),
            (p_config_id, 'S05', 'Soft', TRUE, 5, NULL),
            (p_config_id, 'S06', 'Soft', TRUE, 5, NULL)
        ON CONFLICT (config_id, rule_code) DO NOTHING;
    ELSIF v_schedule_type = 'Exam' THEN
        INSERT INTO constraint_rules (config_id, rule_code, rule_type, is_enabled, weight, param_value)
        VALUES
            (p_config_id, 'E01', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'E02', 'Hard', TRUE, 0, 2),
            (p_config_id, 'E03', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'E04', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'E05', 'Hard', TRUE, 0, NULL),
            (p_config_id, 'ES01', 'Soft', TRUE, 5, NULL),
            (p_config_id, 'ES02', 'Soft', TRUE, 5, NULL),
            (p_config_id, 'ES03', 'Soft', TRUE, 5, NULL)
        ON CONFLICT (config_id, rule_code) DO NOTHING;
    END IF;
END;
$$;

